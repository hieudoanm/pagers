//! `pagers init`: scaffold a starter project — a `docs/` directory with a
//! landing page, a guide section and a `pagers.yaml`.

use std::path::Path;

const INDEX: &str = "---\ntitle: My Docs\ndescription: Written with pagers.\n---\n\n# Welcome\n\nThis site was generated by `pagers build`.\n\n- [Getting started](getting-started.md)\n- [Installation guide](guide/installation.md)\n- [Page graph](graph.html)\n";

const GETTING_STARTED: &str = "# Getting started\n\nEdit the Markdown files in `docs/` and rebuild:\n\n```bash\npagers build docs\n```\n\n> [!TIP]\n> Add pages by dropping `.md` files into the folder — navigation updates automatically.\n";

const GUIDE_INDEX: &str = "# Guide\n\nLonger-form documentation lives here.\n";

const INSTALLATION: &str = "# Installation\n\n```bash\ncargo install --path /path/to/pagers\n```\n\nSee the [home page](../index.md) for an overview.\n";

const CONFIG: &str = "# Site configuration — all fields optional.\n# title: My Docs\n# language: en\n# basePath: /docs\n# theme: light\n# footer: \"© Example\"\n";

/// Creates `dir/docs` with example content. Existing files are left alone.
pub fn init(dir: &str) -> Result<(), String> {
    let docs = Path::new(dir).join("docs");
    std::fs::create_dir_all(docs.join("guide"))
        .map_err(|e| format!("create {}: {e}", docs.display()))?;

    let files = [
        ("index.md", INDEX),
        ("getting-started.md", GETTING_STARTED),
        ("guide/index.md", GUIDE_INDEX),
        ("guide/installation.md", INSTALLATION),
        ("pagers.yaml", CONFIG),
    ];
    for (name, contents) in files {
        let path = docs.join(name);
        if path.exists() {
            continue;
        }
        std::fs::write(&path, contents).map_err(|e| format!("write {}: {e}", path.display()))?;
    }
    println!("Created {}", docs.display());
    println!("Next: pagers build {}", docs.display());
    Ok(())
}
