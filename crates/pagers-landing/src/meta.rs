//! Site metadata files emitted beside the built page: favicon, robots,
//! sitemap, humans.txt, webmanifest and llms.txt. Files already present in
//! the output directory are left untouched — a custom favicon or robots.txt
//! always wins over the generated default.

use crate::config::{Config, Theme};
use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

/// Metadata files written for a build, in stable order.
#[derive(Debug, Default)]
pub struct MetaResult {
    pub files: Vec<PathBuf>,
}

/// Write the metadata set into the directory containing `output`.
/// Returns the paths actually written (existing files are skipped).
pub fn write_meta(cfg: &Config, output: &Path) -> Result<MetaResult, std::io::Error> {
    let dir = output.parent().unwrap_or_else(|| Path::new("."));
    let url = page_url(cfg);
    let mut files = Vec::new();
    for (name, body) in [
        ("favicon.svg", favicon_svg(cfg)),
        ("robots.txt", robots_txt(&url)),
        ("sitemap.xml", sitemap_xml(&url)),
        ("humans.txt", humans_txt(cfg)),
        ("site.webmanifest", webmanifest(cfg)),
        ("llms.txt", llms_txt(cfg, &url)),
    ] {
        let path = dir.join(name);
        if path.exists() {
            continue;
        }
        std::fs::write(&path, body)?;
        files.push(path);
    }
    Ok(MetaResult { files })
}

/// Absolute page URL for sitemap/robots/llms: `site.og.url` when set,
/// otherwise "/" — correct once deployed under a real base path.
fn page_url(cfg: &Config) -> String {
    let og = cfg.social();
    let url = og.url.trim().trim_end_matches('/');
    if url.is_empty() {
        "/".to_string()
    } else {
        url.to_string()
    }
}

fn xml_escape(s: &str) -> String {
    s.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
        .replace('\'', "&apos;")
}

/// SVG favicon: theme-primary rounded square with the site mark (emoji) or
/// the site's initial. Emoji survives because browsers rasterize SVG text.
fn favicon_svg(cfg: &Config) -> String {
    let primary = if cfg.theme.primary.is_empty() {
        Theme::default().primary
    } else {
        cfg.theme.primary.clone()
    };
    let glyph = if !cfg.site.mark.trim().is_empty() {
        cfg.site.mark.trim().to_string()
    } else {
        cfg.site
            .name
            .chars()
            .find(|c| c.is_alphanumeric())
            .map(|c| c.to_uppercase().next().unwrap_or(c).to_string())
            .unwrap_or_else(|| "?".into())
    };
    format!(
        "<svg xmlns=\"http://www.w3.org/2000/svg\" viewBox=\"0 0 64 64\">\n  <rect width=\"64\" height=\"64\" rx=\"14\" fill=\"{}\"/>\n  <text x=\"32\" y=\"44\" font-size=\"34\" text-anchor=\"middle\">{}</text>\n</svg>\n",
        xml_escape(&primary),
        xml_escape(&glyph)
    )
}

fn robots_txt(url: &str) -> String {
    let mut s = String::from("User-agent: *\nAllow: /\n");
    if url != "/" {
        s.push_str(&format!("\nSitemap: {url}/sitemap.xml\n"));
    }
    s
}

fn sitemap_xml(url: &str) -> String {
    // Directory-style pages canonicalize with a trailing slash.
    let loc = if url == "/" {
        "/".to_string()
    } else {
        format!("{url}/")
    };
    format!(
        "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n<urlset xmlns=\"http://www.sitemaps.org/schemas/sitemap/0.9\">\n  <url><loc>{}</loc></url>\n</urlset>\n",
        xml_escape(&loc)
    )
}

fn humans_txt(cfg: &Config) -> String {
    let mut s = format!(
        "/* SITE */\n{}\n{}\n\n/* TECHNOLOGY */\nGenerated by pagers landing — a single-file static landing page.\n",
        cfg.site.name,
        cfg.site.description
    );
    let year = chrono_year();
    s.push_str(&format!("\n/* UPDATED */\n{year}\n"));
    s
}

fn webmanifest(cfg: &Config) -> String {
    let mut map = BTreeMap::new();
    map.insert("name", cfg.site.name.clone());
    map.insert(
        "short_name",
        cfg.site
            .name
            .split_whitespace()
            .next()
            .unwrap_or(&cfg.site.name)
            .to_string(),
    );
    map.insert("description", cfg.site.description.clone());
    let primary = if cfg.theme.primary.is_empty() {
        Theme::default().primary
    } else {
        cfg.theme.primary.clone()
    };
    map.insert("theme_color", primary);
    map.insert("background_color", cfg.theme.base.clone());
    map.insert("start_url", ".".to_string());
    map.insert("display", "standalone".to_string());
    let icons =
        serde_json::json!([{ "src": "favicon.svg", "sizes": "any", "type": "image/svg+xml" }]);
    let mut v = serde_json::Map::new();
    for (k, val) in map {
        v.insert(k.to_string(), serde_json::Value::String(val));
    }
    v.insert("icons".to_string(), icons);
    format!(
        "{}\n",
        serde_json::to_string_pretty(&serde_json::Value::Object(v)).unwrap_or_default()
    )
}

fn llms_txt(cfg: &Config, url: &str) -> String {
    format!(
        "# {}\n\n> {}\n\n## Page\n\n- [{}]({}): {}\n",
        cfg.site.name, cfg.site.description, cfg.site.name, url, cfg.site.description
    )
}

fn chrono_year() -> u32 {
    // Days since epoch → civil year (Howard Hinnant's algorithm), UTC.
    let secs = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_secs())
        .unwrap_or(0);
    let days = (secs / 86_400) as i64;
    let z = days + 719_468;
    let era = if z >= 0 { z } else { z - 146_096 } / 146_097;
    let doe = z - era * 146_097;
    let yoe = (doe - doe / 1460 + doe / 36_524 - doe / 146_096) / 365;
    let y = yoe + era * 400;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let _mp = (5 * doy + 2) / 153;
    (y + if _mp < 10 { 0 } else { 1 }) as u32
}
