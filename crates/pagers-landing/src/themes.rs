//! The 64 built-in theme presets (gallery order). Port of `internal/landify/themes.go`.

use crate::config::Theme;

/// A named theme preset with a one-line description.
#[derive(Debug, Clone)]
pub struct NamedTheme {
    pub name: &'static str,
    pub description: &'static str,
    pub theme: Theme,
}

/// Const-friendly literal form so presets can live in a `const` table.
#[derive(Debug, Clone, Copy)]
struct ThemeLit {
    base: &'static str,
    primary: &'static str,
    secondary: &'static str,
    neutral: &'static str,
    info: &'static str,
    warning: &'static str,
    success: &'static str,
    error: &'static str,
    radius: &'static str,
}

impl From<ThemeLit> for Theme {
    fn from(l: ThemeLit) -> Self {
        Theme {
            base: l.base.into(),
            primary: l.primary.into(),
            secondary: l.secondary.into(),
            neutral: l.neutral.into(),
            info: l.info.into(),
            warning: l.warning.into(),
            success: l.success.into(),
            error: l.error.into(),
            radius: l.radius.into(),
        }
    }
}

