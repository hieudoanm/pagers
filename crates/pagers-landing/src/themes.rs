/// All presets in gallery order.
pub fn themes() -> Vec<NamedTheme> {
    ENTRIES
        .iter()
        .map(|e| NamedTheme {
            name: e.name,
            description: e.description,
            theme: e.theme.into(),
        })
        .collect()
}

/// Resolve `name` (case-insensitive) to its Theme.
pub fn theme_by_name(name: &str) -> Option<Theme> {
    ENTRIES
        .iter()
        .find(|e| e.name.eq_ignore_ascii_case(name))
        .map(|e| e.theme.into())
}

/// Theme names in alphabetical order.
pub fn theme_names() -> Vec<&'static str> {
    let mut names: Vec<&'static str> = ENTRIES.iter().map(|e| e.name).collect();
    names.sort_unstable();
    names
}
